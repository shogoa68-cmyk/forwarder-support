-- ============================================================
-- 不具合報告（フィードバック拡張）：添付（スクショ・動画）／対応状況／画面情報
-- Supabase の SQL Editor で実行（何度実行しても安全＝冪等）
-- 前提：feedbacks テーブル・is_team_member() 関数・pg_cron（添付の自動削除用）
-- ============================================================

-- ① feedbacks に列を追加（未適用でもアプリは従来どおり動く＝テキストのみ送信にフォールバック）
alter table public.feedbacks
  add column if not exists report_no       bigint generated by default as identity,  -- 画面表示用の連番（#12）
  add column if not exists title           text,                                     -- 一行要約（任意）
  add column if not exists reporter_email  text,                                     -- 報告者（ログイン時のみ）
  add column if not exists page_url        text,                                     -- 報告時のURL
  add column if not exists context         jsonb not null default '{}'::jsonb,       -- 画面/タブ/ブラウザ/コンソールエラー等
  add column if not exists attachments     jsonb not null default '[]'::jsonb,       -- [{path,name,type,size,kind}]
  add column if not exists response        text,                                     -- 対応メモ（報告者・チームに表示）
  add column if not exists responded_by    text,
  add column if not exists responded_at    timestamptz,
  add column if not exists updated_at      timestamptz not null default now();

-- ステータス：open(未対応) / in_progress(対応中) / resolved(解決済み) / wontfix(対応しない)
-- 既存の check 制約が無い前提（text のまま）。

-- ② チームメンバーは全件閲覧・更新可（既存ポリシーと同一。再作成しても安全）
grant select, update on public.feedbacks to authenticated;
drop policy if exists "team members can view all feedbacks" on public.feedbacks;
create policy "team members can view all feedbacks"
  on public.feedbacks for select to authenticated using (is_team_member());
drop policy if exists "team members can update feedback status" on public.feedbacks;
create policy "team members can update feedback status"
  on public.feedbacks for update to authenticated
  using (is_team_member()) with check (is_team_member());

-- ③ 更新時に updated_at を更新し、対応メモが変わったら記入者・時刻を記録
create or replace function public.feedbacks_touch()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.updated_at := now();
  if new.response is distinct from old.response then
    new.responded_by := auth.email();
    new.responded_at := now();
  end if;
  return new;
end; $$;
drop trigger if exists feedbacks_touch_trg on public.feedbacks;
create trigger feedbacks_touch_trg before update on public.feedbacks
  for each row execute function public.feedbacks_touch();

-- ④ 添付用ストレージ（非公開・1ファイル50MBまで・画像/動画のみ）
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
  values ('feedback-attachments', 'feedback-attachments', false, 52428800,
          array['image/png','image/jpeg','image/webp','image/gif','video/webm','video/mp4','video/quicktime'])
  on conflict (id) do nothing;

-- ログイン済みのチームメンバーのみ 追加・閲覧・削除（画面に顧客名や運賃が写る可能性があるため）
drop policy if exists "fbatt obj select" on storage.objects;
create policy "fbatt obj select" on storage.objects for select to authenticated
  using (bucket_id = 'feedback-attachments' and is_team_member());
drop policy if exists "fbatt obj insert" on storage.objects;
create policy "fbatt obj insert" on storage.objects for insert to authenticated
  with check (bucket_id = 'feedback-attachments' and is_team_member());
drop policy if exists "fbatt obj delete" on storage.objects;
create policy "fbatt obj delete" on storage.objects for delete to authenticated
  using (bucket_id = 'feedback-attachments' and is_team_member());

-- ⑤ 容量対策：90日を過ぎた添付ファイルは自動削除（報告の本文・対応状況は残る）
create extension if not exists pg_cron;
create or replace function public.purge_expired_feedback_attachments()
returns void language plpgsql security definer set search_path = public, storage as $$
begin
  delete from storage.objects
    where bucket_id = 'feedback-attachments' and created_at < now() - interval '90 days';
end; $$;
do $$ begin
  perform cron.unschedule(jobid) from cron.job where jobname = 'purge-feedback-attachments';
exception when others then null; end $$;
select cron.schedule('purge-feedback-attachments', '10 18 * * *', $$select public.purge_expired_feedback_attachments();$$);
